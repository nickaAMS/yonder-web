#!/usr/bin/env python3
"""Build demo/v2-full.html: variant B's opening (title-cast.html) followed by variant A (index.html) from the
book onward. Run from redesign-2026-11/:  python3 lab/build_v2.py
A and B stay the sources; v2-full.html is generated, so edit those and re-run rather than editing the output."""
import re
A = open('demo/index.html').read()
B = open('demo/title-cast.html').read()

def ren(t):          # names that clash with variant A
    t = t.replace('#hero', '#opening')
    t = re.sub(r'\.stage\b', '.bstage', t)
    t = re.sub(r'\.cue\b', '.bcue', t)
    return t

# --- B's styles: everything from its hero rule to the header-link block, minus the header it shares with A
css = B[B.index('  #hero { position:relative;'):B.index('  /* header links, on the valance')]
css = '\n'.join(l for l in css.split('\n') if not re.match(r'\s*\.(top|valance|wordmark|curtain)\b', l) and not l.strip().startswith('-webkit-mask:') and not l.strip().startswith('mask:'))
css = ren(css)
bcls = set(re.findall(r'\.([a-z][a-z0-9-]*)', css)) - {'bstage', 'bcue', 'caps', 'cta', 'l1', 'l2', 'w', 'a', 'b', 'on', 'l', 'r', 'm'}
acss = A[A.index('<style>'):A.index('</style>')]
clash = sorted(c for c in bcls if re.search(r'\.%s\b' % re.escape(c), acss))
print('class names used by both (check):', clash)

# --- B's opening section
sec = B[B.index('<section id="hero">'):B.index('</section>', B.index('<section id="hero">')) + len('</section>')]
sec = sec.replace('<section id="hero">', '<section id="opening">').replace('class="stage" id="stage"', 'class="bstage" id="bstage"').replace('class="cue caps" id="cue"', 'class="bcue caps" id="bcue"')
slip3 = sec[sec.index('<p><b>Tomorrow</b>'):sec.index('</p>', sec.index('<p><b>Tomorrow</b>')) + 4]
sec = sec.replace(slip3, slip3 + '\n          <p><b>And then</b>Every adventure becomes a book of their own. Back to tonight&rsquo;s.</p>')
assert 'bstage' in sec and 'bcue' in sec and 'And then' in sec

# --- B's script
js = B[B.index('<script>') + 8:B.rindex('</script>')]
js = js.replace("getElementById('hero')", "getElementById('opening')").replace("getElementById('cue')", "getElementById('bcue')").replace("getElementById('stage')", "getElementById('bstage')")
old = "var w = p < .5 ? 0 : p < .7 ? 1 : 2;"; assert js.count(old) == 1
js = js.replace(old, "var w = p < .5 ? 0 : p < .7 ? 1 : p < .955 ? 2 : 3;")

# --- A, starting its first act at the book
OVR = '''
  /* ===== V2 (generated by lab/build_v2.py): variant B's opening, then this page from the book onward ===== */
''' + css + '''
  #opening { height:740vh; }
  #hero { height:330vh; }
  .house, .onc, #copy, #cue, .fig .tagwrap, .fig .chip, .fig.extra { display:none !important; }
  @media (max-width:760px) { #opening { height:470vh; } #hero { height:230vh; } }
  @media (prefers-reduced-motion:reduce) { #opening, #hero { height:auto; } .bstage { position:relative; } .bcue { display:none; } }
'''
out = A
i = out.rindex('</style>'); out = out[:i] + OVR + out[i:]
mark = '<!-- 1. THE STORY IS CAST -->'; assert out.count(mark) == 1
out = out.replace(mark, '<!-- 0. VARIANT B OPENING: THE CAST IN THE TITLE -->\n' + sec + '\n\n' + mark)
old = '<div class="inv-head a"><p class="caps">Tonight&rsquo;s story</p><h2>The cast</h2></div>'; assert out.count(old) == 1
out = out.replace(old, '<div class="inv-head a"><p class="caps">Back to tonight&rsquo;s story</p><h2>Every adventure becomes a book.</h2></div>')
i = out.index('<script>\n(function(){'); out = out[:i] + '<script>window.NS_START = .7;   /* the first act of variant A begins with the cast already in the forest */</script>\n' + out[i:]
i = out.rindex('</body>'); out = out[:i] + '<script>' + js + '</script>\n' + out[i:]
out = out.replace('<title>Namesake redesign demo</title>', '<title>Namesake redesign demo: cast in the title, full page</title>')
open('demo/v2-full.html', 'w').write(out)
print('wrote demo/v2-full.html', len(out))
